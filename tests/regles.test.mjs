import { initializeTestEnvironment, assertSucceeds, assertFails } from "@firebase/rules-unit-testing";
import { readFileSync } from "fs";
import { doc, setDoc, getDoc, updateDoc, getDocs, collection, addDoc, deleteDoc, serverTimestamp, deleteField } from "firebase/firestore";

const rules = readFileSync(new URL("../firestore.rules", import.meta.url), "utf8").replace("\"PROPRIETAIRE_UID\"", "\"OWNER1\"");
const env = await initializeTestEnvironment({ projectId: "demo-rules", firestore: { rules, host: "127.0.0.1", port: 8080 } });
await env.clearFirestore();
const owner = env.authenticatedContext("OWNER1").firestore();
const ali = env.authenticatedContext("ali").firestore();
const bob = env.authenticatedContext("bob").firestore();
const anon = env.unauthenticatedContext().firestore();
const fresh = (name) => ({ name, email: name + "@x.sn", created: serverTimestamp(), lastSeen: serverTimestamp(), active: true, role: "joueur", poste: "" });
let n = 0, bad = 0;
const t = async (label, p) => { n++; try { await p; console.log("ok  ", label); } catch (e) { bad++; console.log("FAIL", label, e.message); } };

await t("client crée sa fiche", assertSucceeds(setDoc(doc(ali, "users/ali"), fresh("Ali"))));
await t("client ne crée pas la fiche d'un autre", assertFails(setDoc(doc(ali, "users/zoe"), fresh("Zoe"))));
await t("client ne se crée pas suspendu/actif à sa guise (active false refusé)", assertFails(setDoc(doc(bob, "users/bob"), { ...fresh("Bob"), active: false })));
await t("client ne met pas de champ en plus", assertFails(setDoc(doc(bob, "users/bob"), { ...fresh("Bob"), admin: true })));
await t("client ne triche pas sur la date d'inscription", assertFails(setDoc(doc(bob, "users/bob"), { ...fresh("Bob"), created: new Date(2020, 0, 1) })));
await t("bob crée sa fiche", assertSucceeds(setDoc(doc(bob, "users/bob"), fresh("Bob"))));
await t("client lit sa fiche", assertSucceeds(getDoc(doc(ali, "users/ali"))));
await t("client ne lit pas la fiche d'un autre", assertFails(getDoc(doc(ali, "users/bob"))));
await t("client ne liste pas les comptes", assertFails(getDocs(collection(ali, "users"))));
await t("visiteur ne lit rien", assertFails(getDocs(collection(anon, "users"))));
await t("client change son nom", assertSucceeds(updateDoc(doc(ali, "users/ali"), { name: "Ali D.", lastSeen: serverTimestamp() })));
await t("client ne se réactive/suspend pas lui-même", assertFails(updateDoc(doc(ali, "users/ali"), { active: false })));
await t("client ne change pas sa date d'inscription", assertFails(updateDoc(doc(ali, "users/ali"), { created: new Date(2020, 0, 1) })));
await t("client ne modifie pas un autre compte", assertFails(updateDoc(doc(ali, "users/bob"), { name: "pirate", lastSeen: serverTimestamp() })));
await t("propriétaire liste les comptes", assertSucceeds(getDocs(collection(owner, "users"))));
await t("propriétaire suspend bob", assertSucceeds(updateDoc(doc(owner, "users/bob"), { active: false })));
await t("propriétaire ne change pas autre chose que active", assertFails(updateDoc(doc(owner, "users/ali"), { name: "x" })));
await t("compte suspendu ne peut plus écrire sa fiche", assertFails(updateDoc(doc(bob, "users/bob"), { name: "Bob", lastSeen: serverTimestamp() })));
await t("compte suspendu lit encore sa fiche (pour voir qu'il est suspendu)", assertSucceeds(getDoc(doc(bob, "users/bob"))));
await t("propriétaire réactive bob", assertSucceeds(updateDoc(doc(owner, "users/bob"), { active: true })));
await t("personne ne supprime un compte", assertFails(deleteDoc(doc(owner, "users/bob"))));
const err = (uid) => ({ kind: "plantage", message: "boom", page: "planning", uid, name: "", ua: "test", at: serverTimestamp() });
await t("client connecté écrit une erreur", assertSucceeds(addDoc(collection(ali, "errors"), err("ali"))));
await t("visiteur écrit une erreur anonyme", assertSucceeds(addDoc(collection(anon, "errors"), err(null))));
await t("on ne signe pas une erreur au nom d'un autre", assertFails(addDoc(collection(ali, "errors"), err("bob"))));
await t("erreur au format libre refusée", assertFails(addDoc(collection(ali, "errors"), { ...err("ali"), kind: "pub" })));
await t("client ne lit pas le journal", assertFails(getDocs(collection(ali, "errors"))));
const snap = await getDocs(collection(owner, "errors"));
await t("propriétaire lit le journal (" + snap.size + " erreurs)", Promise.resolve(snap.size === 2 || Promise.reject(new Error("taille " + snap.size))));
await t("client n'efface pas une erreur", assertFails(deleteDoc(doc(ali, "errors/" + snap.docs[0].id))));
await t("propriétaire efface une erreur", assertSucceeds(deleteDoc(doc(owner, "errors/" + snap.docs[0].id))));
await t("autre collection fermée", assertFails(setDoc(doc(owner, "autre/x"), { a: 1 })));
console.log(`\n${n - bad}/${n} tests passés`);
await env.cleanup();
process.exit(bad ? 1 : 0);
